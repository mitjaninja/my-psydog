// Слова и фразы, при которых после сохранения заметки показываем кризисный экран.
// Совпадение — подстрока после нормализации (регистр, ё → е, пробелы), поэтому
// «суицид» ловит и «суицидальные». Лучше лишний раз показать контакты помощи.
// TODO: проверка списка специалистом.
export const CRISIS_KEYWORDS = [
  'суицид',
  'самоубийств',
  'покончить с собой',
  'покончу с собой',
  'убить себя',
  'убью себя',
  'не хочу жить',
  'не хочется жить',
  'жить не хочу',
  'хочу умереть',
  'лучше бы я умер',
  'лучше бы меня не было',
  'свести счеты с жизнью',
  'нет смысла жить',
  'незачем жить',
  'повеситься',
  'повешусь',
  'вскрыть вены',
  'порезать себя',
  'режу себя',
  'самоповрежд',
  'выпрыгнуть из окна',
  'спрыгнуть с крыши',
  'наглотаться таблеток',
  'не вижу выхода',
];

export function normalizeText(text: string): string {
  return text.toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();
}

const NORMALIZED = CRISIS_KEYWORDS.map(normalizeText);

export function hasCrisisKeywords(text: string | undefined | null): boolean {
  if (!text) return false;
  const t = normalizeText(text);
  return NORMALIZED.some((k) => t.includes(k));
}
